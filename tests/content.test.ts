const RELEASE = import.meta.env.MODE === 'release';
// Fractions stay one token ("2/3"): in numeric-expression pages the numbers are the meaning.
const tokens = (s: string) => new Set(s.toLowerCase().match(/[a-z]+|\d+(?:\/\d+)?/g) ?? []);
const jaccard = (a: string, b: string) => {
  const A = tokens(a);
  const B = tokens(b);
  const inter = [...A].filter((x) => B.has(x)).length;
  return inter / (A.size + B.size - inter);
};

describe('registry (generated by clustering)', () => {
  test('every URL is unique, well formed, and in a known category', () => {
    const urls = REGISTRY.map((r) => r.url);
    expect(new Set(urls).size).toBe(urls.length);
    for (const r of REGISTRY) {
      expect(r.url).toMatch(/^\/[a-z-]+\/[a-z0-9-]+\/(?:[a-z0-9-]+\/)?$/);
      expect(CATEGORY_SLUGS).toContain(r.category as (typeof CATEGORY_SLUGS)[number]);
    }
  });
  test('every keyword (primary or secondary) is owned by exactly one URL', () => {
    const owner = new Map<string, string>();
    for (const r of REGISTRY) for (const k of [r.primary, ...r.secondary]) {
      expect(owner.get(k), `"${k}" claimed by ${r.url} and ${owner.get(k)}`).toBeUndefined();
      owner.set(k, r.url);
    }
  });
  test('guides never say "calculator" in their primary keyword', () => {
    for (const r of REGISTRY.filter((x) => x.type === 'guide')) expect(r.primary).not.toMatch(/calculator/i);
  });
  test('calculators never target numeric-expression queries (those are instances)', () => {
    for (const r of REGISTRY.filter((x) => x.type === 'calculator')) for (const k of [r.primary, ...r.secondary]) expect(k, r.url).not.toMatch(/\d\s*\/\s*\d|\b\d+ days from\b/);
  });
  test('not-green rows are never publishable (AdSense green flag)', () => {
    for (const r of REGISTRY.filter((x) => x.adsense !== 'green')) expect(isPublishableRow(r)).toBe(false);
  });
});

